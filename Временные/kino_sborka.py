def sobrat(dannye, fayl):
    gotovye = []
    for imya, video in dannye['подборки']:
        ryady = []
        for podpis, kod, zachem in video:
            v = s_video(kod)
            ryady.append([podpis, kod, v['секунд'],
                          ' · '.join(x for x in [v['название'], zachem,
                                                 v['канал'],
                                                 (str(v['возраст']) + '+'
                                                  if v['возраст'] else '')]
                                     if x)])
            time.sleep(0.3)
        gotovye.append({'имя': imya, 'видео': ryady})
        print(f'  {fayl}: {imya} — {len(ryady)}')
    zapis = {'_что': dannye['_зачем'],
             'заголовок': dannye['заголовок'],
             'подзаголовок': dannye['подзаголовок'],
             'источник': 'Rutube',
             'проверено': time.strftime('%Y-%m-%d'),
             'подборки': gotovye}
    io.open(os.path.join(os.path.dirname(__file__), fayl), 'w',
            encoding='utf-8').write(
        json.dumps(zapis, ensure_ascii=False, indent=1) + '\n')


