UA = ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
      '(KHTML, like Gecko) Chrome/124 Safari/537.36')


def s_video(kod):
    """Название, длительность и возраст ролика — как их отдаёт Rutube."""
    import urllib.request
    r = urllib.request.Request(API.format(kod),
                               headers={'User-Agent': UA,
                                        'Referer': 'https://rutube.ru/',
                                        'Accept': 'application/json'})
    d = json.load(urllib.request.urlopen(r, timeout=40))
    return {'название': d['title'], 'секунд': d['duration'],
            'возраст': ((d.get('pg_rating') or {}).get('age') or ''),
            'канал': (d.get('author') or {}).get('name') or ''}


