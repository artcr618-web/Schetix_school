# -*- coding: utf-8 -*-
"""Разметка: модели экранов и раскладка плашек.

ЕДИНСТВЕННОЕ место, где записано, сколько плашек в ряд на каждой модели
экрана и какого они размера. Отсюда берётся всё:

  * `setka_css()` — CSS сетки плашек; его подставляет _tv.py в каждую
    страницу при сборке, поэтому в самих страницах этот блок править
    нельзя — перезапишется;
  * `zapisat()` — Временные/разметка.json для проверки
    (Временные/proverka_setki.js): сверка вёрстки идёт по той же таблице,
    по которой она собрана, а не по числам, записанным в проверке руками;
  * таблица моделей — в РАЗМЕТКА.md, для людей.

МОДЕЛЬ ЭКРАНА — как у Тильды. Пять контрольных точек: 320 / 480 / 640 /
960 / 1200. Ниже 320 px страница не ужимается (у Тильды это нижний
артборд). Новых контрольных точек не заводим: вся адаптация идёт только
по этим пяти, иначе вёрстка начинает жить на десятке незаметных порогов.

Шесть моделей (так их называет Тильда и так же называем мы):

    Широкий экран           1440 и шире
    Обычный экран           1200 – 1439
    Планшет горизонтальный   960 – 1199
    Планшет вертикальный     640 –  959
    Телефон горизонтальный   480 –  639
    Телефон вертикальный     320 –  479

Плашки: три в ряд на обоих десктопах, две — на обоих планшетах, одна
во всю ширину — на обоих телефонах. Размер задан долями кадра
(minmax(0, 1fr)), а не пикселями: плашки в ряду всегда одного размера,
ряд заполнен целиком, а при сужении окна они уменьшаются в масштабе.

РАБОЧАЯ ШИРИНА, А НЕ ШИРИНА ОКНА. Модель экрана считается по ширине
той области, где стоят плашки. Открытое боковое меню (и панель
плейлиста на видеоуроках) забирает у страницы своё место: --panel-shirina
уходит в padding-right у body, а ширина страницы — это ОСТАТОК. Раньше
раскладка считалась по окну и меню не замечала: на широком экране с
открытым меню в ряд по-прежнему вставали три плашки, места им не
хватало, и цифры вылезали наружу.

Поэтому раскладка задана контейнерными запросами (@container), а не
медиа: контейнер — внешний блок `.rabochaya` вокруг страницы (см. _tv.CSS),
его ширина и есть рабочая. Открыли меню — рабочая ширина стала меньше,
и плашки перестроились по той же таблице, как если бы окно было ровно
такой ширины. Панели стоят СНАРУЖИ контейнера: внутри него position:fixed
считался бы от него, а не от окна.

Две раскладки в одном файле: контейнерная — основная, медийная — та же
таблица по ширине окна, для браузеров без @container. Порядок важен:
контейнерные блоки идут последними и потому перебивают медийные.
"""

# Контрольные точки Тильды. Их не сдвигаем.
TOCHKI = (1200, 960, 640, 480, 320)

# Ширина, ниже которой страница не ужимается.
DNO = 320

# Шесть моделей экрана: имя, от какой ширины, до какой (включительно).
MODELI = (
    ('Широкий экран',          1440, None),
    ('Обычный экран',          1200, 1439),
    ('Планшет горизонтальный',  960, 1199),
    ('Планшет вертикальный',    640,  959),
    ('Телефон горизонтальный',  480,  639),
    ('Телефон вертикальный',    320,  479),
)

# Раскладка плашек по полосам ширины. Полоса — от одной контрольной
# точки до следующей; `do` — её нижняя граница (включительно), у самой
# широкой полосы границы нет.
#
#   v_ryadu — сколько плашек в ряду
#   gap     — зазор между плашками
#   nazv    — размер названия плашки
#   poyas   — размер подписи под названием
#   polosa  — ширина жёлтой полосы слева
#   radius  — скругление плашки
#   chislo  — размер цифры на плашке класса
#   otstup  — внутренние поля плашки
POLOSY = (
    dict(imya='десктопы', do=None, v_ryadu=3, gap=24,
         nazv=36, poyas=20, polosa=18, radius=22,
         chislo='clamp(110px, 12vw, 186px)', kadr='16 / 9',
         otstup='24px 26px 24px calc(var(--polosa) + 28px)'),
    dict(imya='планшет горизонтальный', do=1199, v_ryadu=2, gap=20,
         nazv=36, poyas=18, polosa=16, radius=18,
         chislo='clamp(110px, 12vw, 186px)', kadr='16 / 9',
         otstup='22px 24px 22px calc(var(--polosa) + 26px)'),
    # Плашка вдвое уже десктопной, поэтому название и подпись здесь
    # мельче: иначе длинные названия («Кино и документалистика») не
    # влезали в ширину.
    #
    # Кадр 3/2, а не 16/9: по высоте самые длинные тексты (название
    # «Кино и документалистика» в три строки плюс подпись в две) в
    # 16/9 не помещались, и заголовок выступал над плашкой. Проверка
    # это и поймала на «Географии» 5 класса при рабочей ширине 640 —
    # самом узком случае полосы: там плашка 285×190 (было 285×161),
    # и тексту хватает места с запасом.
    dict(imya='планшет вертикальный', do=959, v_ryadu=2, gap=18,
         nazv=28, poyas=15, polosa=13, radius=14,
         chislo='clamp(70px, 11vw, 150px)', kadr='3 / 2',
         otstup='20px 22px 20px calc(var(--polosa) + 24px)'),
    # Телефон горизонтальный: плашка во всю ширину, 16/9 хватает.
    dict(imya='телефоны горизонтальные', do=639, v_ryadu=1, gap=16,
         nazv=32, poyas=17, polosa=13, radius=14,
         chislo='clamp(80px, 30vw, 186px)', kadr='16 / 9',
         otstup='22px 24px 22px calc(var(--polosa) + 26px)'),
    # Телефон вертикальный — самая узкая полоса: плашка во всю ширину,
    # но кадр узкий, и длинное название с подписью в 16/9 не
    # помещаются. Плашка становится выше (4/3), оставаясь одного
    # размера с соседями.
    dict(imya='телефоны вертикальные', do=479, v_ryadu=1, gap=16,
         nazv=32, poyas=17, polosa=13, radius=14,
         chislo='clamp(80px, 30vw, 186px)', kadr='4 / 3',
         otstup='22px 24px 22px calc(var(--polosa) + 26px)'),
)

# Высота знака-баннера (вход на страницу лекций) в долях от высоты
# плашки той же полосы. Знак — та же плашка, только во всю ширину и
# выше: сперва его подняли на 30 % от прежней высоты (0.8 × 1.3 = 1.04),
# а после попросили сделать в полтора раза выше плашки. Отсюда 1.04 × 1.5
# = 1.56 — «полторы высоты плашки». Числа берутся те же, что у плашек
# (сколько в ряд, зазор, кадр), поэтому если полоса поедет, знак поедет
# за ней.
ZNAK_DOLYA = 1.56
# Прежние высоты знака — для справки и для тех, кто помнит «на 20 % ниже»
# и «выше плашки на 30 %».
ZNAK_NIZHE = 1 - 0.8
ZNAK_BYLO = 0.8 * 1.3

# Предел ширины самой страницы: на очень широком экране текст не
# растягивается дальше (см. `.wrap` в _tv.CSS — число подставляется
# оттуда же, из этой константы). Нужен и в счёте высоты знака: выше
# предела страница уже не растёт, а формула по одной рабочей ширине
# продолжала бы растить знак.
SHIRINA_STRANICY = 1500

# Поля страницы по краям: на широком экране 44 px, на телефоне 20 px.
# Плашка занимает всю строку, и на телефоне лишние поля съедали бы
# четверть кадра. Считаются по рабочей ширине (cqw — ширина контейнера),
# а не по окну: с открытым меню поля ужимаются вместе со страницей.
POLYA = 'clamp(20px, 4cqw, 44px)'

# Имя контейнера рабочей ширины. По нему запросы находят именно
# страницу, а не другой контейнер (у плеера свой).
KONTEYNER = 'stranica'

# Класс блока, который этот контейнер образует (см. _tv.CSS).
ZONA_KLASS = 'rabochaya'

# С этой ширины ОКНА и уже боковое меню и панель плейлиста
# разворачиваются на всю ширину экрана: вертикальный планшет и оба
# телефона. Половина экрана под меню — это не меню, а обрезанная
# страница; на десктопах и горизонтальном планшете панель по-прежнему
# выезжает справа, и страница перестраивается по остатку.
MENYU_VO_VSYU = 960


def _blok(p, otstup, baza=False, edinica='vw', prefiks=''):
    # Цифра класса задана в долях ширины. В контейнерных ступенях это
    # доля РАБОЧЕЙ ширины (cqw), в запасных (по окну) — доля окна (vw).
    kolonki = f'repeat({p["v_ryadu"]}, minmax(0, 1fr))'
    # display:grid и отступ сверху задаются один раз, в базовой полосе:
    # в ступенях меняются только колонки и размеры.
    osnova = 'display:grid; margin-top:26px; ' if baza else ''
    # `prefiks` — что подставить перед селектором: в контейнерных
    # ступенях ничего, в запасных по атрибуту — имя полосы.
    #
    # Знак-баннер держим на 20 % ниже плашки этой же полосы. Высоту
    # считаем тем же счётом, каким её получает плашка: ширину страницы
    # (100cqw по рабочей ширине или 100vw по окну) минус поля по краям
    # минус зазоры между плашками, делим на число плашек в ряду — это
    # ширина плашки, — и умножаем на долю кадра (9/16, 2/3, 3/4).
    # Селектор знака — с двумя классами (a.banner-znak.s-kartinkoy
    # нарисован так же), поэтому ступени перебивают базовое правило
    # знака независимо от порядка в файле.
    ch, zn = (float(x) for x in p['kadr'].replace(' ', '').split('/'))
    dolya = ZNAK_DOLYA
    polya = POLYA.replace('cqw', edinica)
    shirina = f'min(100{edinica}, {SHIRINA_STRANICY}px)'
    vysota = (f'calc(({shirina} - 2*{polya} - '
              f'{(p["v_ryadu"] - 1) * p["gap"]}px) / {p["v_ryadu"]} * '
              f'{zn / ch:g} * {dolya:g})')
    return (
        f'{otstup}{prefiks}.setka{{{osnova}grid-template-columns:{kolonki}; '
        f'gap:{p["gap"]}px; '
        f'--polosa:{p["polosa"]}px; --radius:{p["radius"]}px}}\n'
        f'{otstup}{prefiks}a.plitka{{aspect-ratio:{p["kadr"]}; '
        f'padding:{p["otstup"]}}}\n'
        # Знак — та же плашка: те же поля, полоса и скругление, те же
        # размеры шрифта. Отличий два: он во всю ширину и выше плашки
        # (ZNAK_DOLYA), поэтому высота считается, а не берётся из кадра.
        f'{otstup}{prefiks}a.banner-znak{{--polosa:{p["polosa"]}px; '
        f'--radius:{p["radius"]}px; height:{vysota}; '
        f'padding:{p["otstup"]}}}\n'
        f'{otstup}{prefiks}a.plitka .nazv, '
        f'{otstup}{prefiks}a.banner-znak .nazv'
        f'{{font-size:{p["nazv"]}px}}\n'
        f'{otstup}{prefiks}a.plitka .poyas, '
        f'{otstup}{prefiks}a.banner-znak .poyas'
        f'{{font-size:{p["poyas"]}px}}\n'
        f'{otstup}{prefiks}a.plitka.klass .nazv .chislo'
        f'{{font-size:{p["chislo"].replace("vw", edinica)}}}')


def setka_css():
    """CSS сетки плашек: базовая полоса, запасной вариант по окну и
    основная раскладка по рабочей ширине."""
    shirokaya = POLOSY[0]
    chasti = [
        '/* РАСКЛАДКА ПЛАШЕК — собрана из Инструменты/разметка.py.\n'
        '   Здесь не править: при сборке блок перезаписывается.\n'
        '   Модели экрана — в РАЗМЕТКА.md.\n'
        '   Ступени идут по РАБОЧЕЙ ширине (ширине области, где стоят\n'
        '   плашки), а не по ширине окна: открытое меню забирает у\n'
        '   страницы свою часть, и плашки считаются по остатку. */',
        _blok(shirokaya, '', baza=True),
    ]
    # Запасной вариант: браузер без @container раскладывает плашки по
    # ширине окна. Так было до правки — меню в расчёт не берётся.
    for p in POLOSY[1:]:
        chasti.append(f'@media (max-width:{p["do"]}px){{\n'
                      f'  /* {p["imya"]}: {p["v_ryadu"]} в ряд (запасная, по окну) */\n'
                      + _blok(p, '  ') + '\n}')
    # Основная раскладка: по рабочей ширине. Идёт последней, поэтому
    # перебивает запасную.
    for p in POLOSY[1:]:
        chasti.append(f'@container {KONTEYNER} (max-width:{p["do"]}px){{\n'
                      f'  /* {p["imya"]}: {p["v_ryadu"]} в ряд */\n'
                      + _blok(p, '  ', edinica='cqw') + '\n}')
    return '\n'.join(chasti)


def zona_css():
    """Запасной путь раскладки для браузеров без @container.

    Контейнерные запросы — основной механизм, но телевизор или старый
    браузер их не знает, и там страница считалась бы по окну — тот самый
    баг, из-за которого цифры вылезали. Поэтому у каждой полосы есть
    близнец: правило по атрибуту `data-polosa` на блоке рабочей ширины.
    Атрибут ставит скрипт (_tv.py) — и только в браузерах без
    контейнерных запросов: где они есть, CSS справляется сам.

    Числа те же самые: обе раскладки собираются из этой таблицы.
    """
    imya_klassa = ZONA_KLASS
    chasti = [
        '/* ЗАПАСНОЙ ПУТЬ РАСКЛАДКИ — для браузеров без контейнерных\n'
        '   запросов. Собрано там же, где ступени по рабочей ширине\n'
        '   (Инструменты/разметка.py). Атрибут data-polosa ставит скрипт. */',
        '@supports not (container-type: inline-size){',
    ]
    for p in POLOSY:
        prefiks = f'.{imya_klassa}[data-polosa="{p["imya"]}"] '
        chasti.append(f'  /* {p["imya"]}: {p["v_ryadu"]} в ряд */\n'
                      + _blok(p, '  ', edinica='vw', prefiks=prefiks))
        # Текст страницы мельчает на той же полосе, что и в ступенях.
        if p['do'] and p['do'] <= 959:
            chasti.append(f'  {prefiks}.wrap{{font-size:26px}}')
    chasti.append('}')
    return '\n'.join(chasti)


def polya_css():
    """Поля страницы: по рабочей ширине, с запасным вариантом по окну."""
    return ('.wrap{padding:22px clamp(20px, 4vw, 44px)}\n'
            f'@supports (width:1cqw){{ .wrap{{padding:22px {POLYA}}} }}')


def menyu_css():
    """Сколько места у страницы забирает открытая панель."""
    # Ручку ширины прячем теми же селекторами, какими её показывает
    # _tv.CSS: правило с той же точностью, но ниже по файлу, перебивает.
    return (f'@media (max-width:{MENYU_VO_VSYU - 1}px){{\n'
            '  /* Вертикальный планшет и телефоны: панель во всю ширину */\n'
            '  body{--panel-shirina:100vw}\n'
            '  body.menu-otkryto, body.pleylist-otkryto{padding-right:0}\n'
            '  body.menu-otkryto .panel-tyanulka.menyu,\n'
            '  body.pleylist-otkryto .panel-tyanulka.pleylista,\n'
            '  .panel-tyanulka{display:none}\n'
            '}')


def polosa_dlya(shirina):
    """Полоса раскладки для ширины окна (для проверок)."""
    for p in reversed(POLOSY[1:]):
        if shirina <= p['do']:
            return p
    return POLOSY[0]


def zapisat():
    """Таблица для проверки: Временные/разметка.json."""
    import json
    import os

    sdvig = os.path.dirname(os.path.abspath(__file__))
    kuda = os.path.join(sdvig, '..', 'Временные', 'разметка.json')
    dannye = {
        'dno': DNO,
        'tochki': list(TOCHKI),
        'modeli': [dict(imya=i, ot=o, do=d) for i, o, d in MODELI],
        'polosy': [dict(imya=p['imya'], do=p['do'],
                        v_ryadu=p['v_ryadu'], nazv=p['nazv'],
                        kadr=p['kadr'])
                   for p in POLOSY],
        # Рабочая ширина: раскладка считается по контейнеру, поэтому
        # проверке нужно знать его имя и границу «меню во всю ширину».
        # Насколько знак лекций выше плашки: проверке это число нужно,
        # чтобы поймать именно 1.04, а не «примерно».
        'znak_dolya': ZNAK_DOLYA,
        'konteyner': KONTEYNER,
        'zona_klass': ZONA_KLASS,
        'menyu_vo_vsyu': MENYU_VO_VSYU,
    }
    with open(kuda, 'w', encoding='utf-8') as f:
        json.dump(dannye, f, ensure_ascii=False, indent=1)
    return kuda


if __name__ == '__main__':
    print('Модели экрана (как у Тильды):')
    for imya, ot, do in MODELI:
        polosa = polosa_dlya(ot)
        print(f'  {imya:<24} {ot}–{do if do else "…":<6} '
              f'плашек в ряд: {polosa["v_ryadu"]}')
    print(f'\nНиже {DNO} px страница не ужимается.')
    print('json для проверок:', zapisat())
