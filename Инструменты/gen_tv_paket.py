def dop_pleylisty(put_ishodnika, karta, key):
    """Дополнительные плейлисты для страницы видеоуроков.

    Основной («по параграфам») собирает `stroit`; здесь — то, что
    лежит в других разделах той же страницы: короткие пересказы,
    разборы домашних заданий, повторение.
    """
    nakaz = VARIANTY.get(key)
    if not nakaz:
        return []
    tekst = io.open(put_ishodnika, encoding='utf-8').read()
    # якоря внутри страницы — не ссылки на файлы: в плейлист не идут
    tekst = re.sub(r'<a[^>]*href="#[^"]*"[^>]*>.*?</a>', '', tekst, flags=re.S)
    out = []
    for imya, razdel, kolonka, vid in nakaz:
        kusok = razdel_html(tekst, razdel)
        if not kusok:
            print(f'    нет раздела «{razdel}»')
            continue
        ryady = (ryady_iz_tablicy(kusok, karta, kolonka) if vid == 'tabl'
                 else ryady_iz_spiska(kusok, karta))
        # «Часть 3» само по себе ни о чём не говорит: дописываем, часть
        # чего именно — название варианта.
        korotkoe = imya.split(':')[0].strip()
        ryady = [(n, (f'{korotkoe}, часть {t.split()[-1]}'
                      if re.match(r'^Часть\s+\d+$', t) else t), h)
                 for n, t, h in ryady]
        ryady = [r for r in ryady if r[2]]
        if ryady:
            out.append((imya, ryady))
        else:
            print(f'    пусто в разделе «{razdel}»')
    return out


def plitka(ssylka, nazv, poyas=None, skolko=None,
           zamena=None, oblozhka=None, klass=False):
    """Одна плашка, одного размера и с одним шрифтом на всех страницах.

    `nazv` — то, к чему ведёт плашка («5 класс», «История», «Видеоуроки»).
    `poyas` — мелкая подпись под названием, она же несёт смысл плашки.
    `zamena` — по какому учебнику собран предмет (только на выборе
    предмета, мелким текстом внизу плашки).
    `oblozhka` — путь к обложке учебника от текущей страницы: она ложится
    фоном самой плашки, а не всей страницы. `klass` — плашка выбора
    класса: цифра на ней во всю высоту, слово — приглушённой подписью.

    Название класса приходит как «5 класс»: цифра набирается отдельно
    и крупнее, слово — с заглавной буквы («5» «Класс»). В названиях
    предметов и материалов цифр нет, там всё как есть.
    """
    cls = 'plitka klass' if klass else 'plitka'
    m = re.match(r'^(\d+)\s+(.*)$', nazv)
    if m:
        slovo = m.group(2)[:1].upper() + m.group(2)[1:]
        nazv_html = (f'<span class="chislo">{m.group(1)}</span>'
                     f'<span class="slovo">{_tv.myagkie(slovo)}</span>')
    else:
        nazv_html = _tv.myagkie(nazv)
    ch = [f'<span class="nazv">{nazv_html}</span>']
    if poyas:
        ch.append(f'<span class="poyas">{_tv.myagkie(poyas)}</span>')
    if skolko:
        ch.append(f'<span class="skolko">{_tv.myagkie(skolko)}</span>')
    if zamena:
        ch.append(f'<span class="zamena">{_tv.myagkie(zamena)}</span>')
    stil = ''
    if oblozhka:
        cls += ' s-kartinkoy'
        stil = f" style=\"--kartinka:url('{oblozhka}')\""
    return f'<a class="{cls}" href="{ssylka}"{stil}>{"".join(ch)}</a>'


