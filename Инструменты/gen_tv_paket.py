def chist(t):
    """Из куска html — чистый текст одной строкой."""
    t = re.sub(r'<[^>]+>', ' ', t)
    t = htmlmod.unescape(t)
    t = re.sub(r'\s+', ' ', t)
    t = re.sub(r'\(\s*\)', '', t)
    t = re.sub(r'\s+([.,;:!?])', r'\1', t)
    return t.strip(' .—–-·')


def bez_ssylok(kusok):
    """Текст куска без текста его ссылок."""
    return chist(re.sub(r'<a\s[^>]*>.*?</a>', '', kusok, flags=re.S))


def ssylki(kusok):
    """Список (href, подпись) из куска html."""
    out = []
    for href, txt in re.findall(r'<a\s[^>]*href="([^"]+)"[^>]*>(.*?)</a>',
                                kusok, re.S):
        out.append((href, chist(txt) or 'Открыть'))
    return out


