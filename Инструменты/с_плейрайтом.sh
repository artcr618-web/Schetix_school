#!/usr/bin/env bash
# Запуск проверки в браузере: гарантирует, что playwright на месте.
# Папка node_modules в снапшоты не попадает, поэтому после каждой
# перезагрузки окружения её приходится ставить заново — этот скрипт
# делает это сам, если её нет.
#
#   bash Инструменты/с_плейрайтом.sh node Временные/proverka_setki.js
set -e
cd "$(dirname "$0")/.."
if [ ! -d Инструменты/внешнее/nodejs/node_modules/playwright ]; then
  echo "— playwright не найден, ставлю (это ~25 секунд) —"
  bash Инструменты/поставить_плейрайт.sh
fi
exec "$@"
