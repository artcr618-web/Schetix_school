# Курс Geliossar лежит в одном плейлисте сразу для 5—11 классов,
# поэтому пятый класс нужно отфильтровать по пометке «5кл».
FILTER_5KL = lambda it: '5кл' in (it['title'] or '')


def para_v_nazvanii(title, n):
    """Про параграф n ли это видео. Умеет спаренные: §6-7, §46/47, §52/53,
    а ещё написание словами — «параграф 12»."""
    t = title or ''
    for m in re.finditer(r'(?:§|[Пп]араграф)\s*([0-9]+)\s*[-–/]\s*([0-9]+)', t):
        if int(m.group(1)) <= n <= int(m.group(2)):
            return True
    for m in re.finditer(r'(?:§|[Пп]араграф)\s*([0-9]+)', t):
        if int(m.group(1)) == n:
            return True
    return False


def nayti(items, n, filtr=None):
    hits = [i for i in items if para_v_nazvanii(i['title'], n)]
    if filtr:
        hits = [i for i in hits if filtr(i)]
    if not hits:
        return None
    def score(i):
        # точное упоминание «§12» лучше, чем попадание в диапазон «§11—13»
        return 2 if re.search(r'(?:§|[Пп]араграф)\s*%d(?!\s*[-–/]\s*[0-9])' % n,
                              i['title'] or '') else 1
    hits.sort(key=lambda i: (-score(i), -(i.get('dur') or 0)))
    return hits[0]


def main():
    L = json.load(io.open(DATA_PLAYLISTS, encoding='utf-8'))
    gel = L['geliossar']['items']
    gdz = L['gdz']['items']

    stroki, net_polnogo, net_kratkogo = [], [], []
    for glava, n, tema in OGLAVLENIE:
        if n is None:
            pol = next((x for x in gel
                        if FILTER_5KL(x) and 'Введение' in x['title']), None)
            kra = next((x for x in gdz
                        if 'Введение' in (x['title'] or '')
                        and 'ВСЕХ' not in (x['title'] or '')), None)
            nom = 'Введ.'
        else:
            pol = nayti(gel, n, FILTER_5KL)
            kra = nayti(gdz, n)
            nom = str(n)
            if not pol:
                net_polnogo.append(nom)
            if not kra:
                net_kratkogo.append(nom)
        stroki.append({'ch': glava, 'n': nom, 'topic': tema,
                       'gel': pol, 'gdz': kra})

    dannye = {
        'rows': stroki,
        'outro': next((x for x in gel
                       if FILTER_5KL(x) and 'Заключение' in x['title']), None),
        'whole': next((x for x in gdz if 'ВСЕХ' in (x['title'] or '')), None),
    }

    os.makedirs(VREM, exist_ok=True)
    io.open(DATA_PARAGRAFY, 'w', encoding='utf-8').write(
        json.dumps(dannye, ensure_ascii=False, indent=1))

    print(f'Строк в таблице:            {len(stroki)}')
    print(f'Нет полного видео:          {net_polnogo or "нет, всё закрыто"}')
    print(f'Нет краткого пересказа:     {net_kratkogo or "нет, всё закрыто"}')
    print(f'Заключение:                 {(dannye["outro"] or {}).get("url")}')
    print(f'Весь учебник одним видео:   {(dannye["whole"] or {}).get("url")}')
    print(f'\nСохранено: {DATA_PARAGRAFY}')
    if net_polnogo or net_kratkogo:
        print('\nВНИМАНИЕ: есть пропуски, таблица на странице будет с дырками.')
        return 1
    return 0


