def knopki(spisok):
    """[(подпись, url, длительность|None)] → html кнопок."""
    out = []
    for podpis, url, dl in spisok:
        t = f'{podpis} <span class="vremya">{dl}</span>' if dl else podpis
        out.append(f'<a class="btn" href="{url}">{t}</a>')
    return f'<div class="btnrow">{"".join(out)}</div>'


def plural(n, formy):
    """1 тест, 2 теста, 5 тестов."""
    n = abs(n) % 100
    if 11 <= n <= 14:
        return formy[2]
    n %= 10
    if n == 1:
        return formy[0]
    if 2 <= n <= 4:
        return formy[1]
    return formy[2]


