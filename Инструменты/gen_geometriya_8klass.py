def mm(s):
    """Секунды → «12 мин»."""
    return f'{int(s) // 60} мин'


def knopki_iz(spisok):
    """[(подпись, плейлист, начало)] или [(подпись, url, секунды)] → html."""
    out = []
    for x in spisok:
        if len(x) == 3 and isinstance(x[1], int):
            p, pid, nach = x
            v = video(pid, nach)
            out.append((p, v['url'], mm(v['duration'])))
        else:
            p, url, sec = x
            out.append((p, url, mm(sec)))
    return knopki(out)


def chasov(s):
    """Секунды → «3 ч 49 мин»."""
    h, m = int(s) // 3600, (int(s) % 3600) // 60
    return f'{h} ч {m} мин' if h else f'{m} мин'


def video(pid, nachalo):
    """Видео из плейлиста по началу названия."""
    for v in PLST[pid]:
        if v['title'].startswith(nachalo):
            return v
    raise SystemExit(f'НЕ НАЙДЕНО видео: плейлист {pid}, «{nachalo}»')


