#!/usr/bin/env bash
# Полный прогон: собрать заново обе страницы 5 класса и проверить всё.
#
#   ./Инструменты/собрать_историю_5класс.sh
#
# Останавливается на первой ошибке (set -e). Если проверка вёрстки или
# ссылок сказала «плохо», файлы уже перезаписаны — но это не страшно:
# всё пересобирается из данных,.orig-копии не нужны.

set -e
cd "$(dirname "$0")/.."

echo "── 1/6  Вытаскиваем видео из плейлистов Rutube"
python3 "Инструменты/rutube_playlist.py"

echo "── 2/6  Сверяем видео с параграфами учебника"
python3 "Инструменты/sverka_paragrafov.py"

echo "── 3/6  Собираем страницу «Видео по параграфам»"
python3 "Инструменты/gen_video_5klass.py"

echo "── 4/6  Собираем страницу «Кино и документалистика»"
python3 "Инструменты/gen_kino_5klass.py"

echo "── 5/6  Проверяем вёрстку всех страниц"
python3 "Инструменты/proverka_html.py"

echo "── 6/6  Проверяем все ссылки (это долго, минуты две)"
python3 "Инструменты/proverka_ssylok.py"

echo
echo "Готово."
