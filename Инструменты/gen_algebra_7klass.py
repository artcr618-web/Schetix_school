def komplekty(chast):
    """Строки таблицы → комплекты (вариант 1 + ответы + вариант 2 + ответы)."""
    out = []
    for stroka in chast['komplekty']:
        perv = stroka['ssylki'][0][0].lower() if stroka['ssylki'] else ''
        if ('вариант 2' in perv or 'variant 2' in perv) and out:
            out[-1].extend(stroka['ssylki'])
        else:
            out.append(list(stroka['ssylki']))
    return out


